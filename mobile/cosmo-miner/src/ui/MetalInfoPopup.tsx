type Props = {
  metalInfoOpenId: MetalId | null;
  onClose: () => void;
};

export function MetalInfoPopup({ metalInfoOpenId, onClose }: Props) {
  const metal = metalInfoOpenId
    ? getMetals().find((m) => m.id === metalInfoOpenId)
    : null;
  const info = metalInfoOpenId ? METAL_INFO[metalInfoOpenId] : null;

  return (
    <Popup
      visible={metalInfoOpenId !== null}
      title={info?.title ?? ''}
      onClose={() => {
        logEvent('toast_close', { toast: 'metal_info', metalId: metalInfoOpenId });
        onClose();
      }}
      image={metal?.image}
      text={info?.text ?? ''}
      clerk
    />
  );
}
